export type Lang = keyof typeof DICT;
export type I18nKey = keyof (typeof DICT)["en"];

const LangContext = React.createContext<{ lang: Lang; setLang: (l: Lang) => void }>({
  lang: "en",
  setLang: () => {},
});

export function readLangCookie(): Lang {
  if (typeof document === "undefined") return "en";
  const m = document.cookie.match(/(?:^|;\s*)exai_lang=([^;]+)/);
  return m && (m[1] === "en" || m[1] === "fr") ? m[1] : "en";
}

export function I18nProvider({ children }: { children: React.ReactNode }) {
  const [lang, setLangState] = React.useState<Lang>(() => readLangCookie());
  const setLang = React.useCallback((l: Lang) => {
    document.cookie = `exai_lang=${l}; path=/; max-age=${60 * 60 * 24 * 365}`;
    setLangState(l);
    window.location.reload();
  }, []);
  return <LangContext.Provider value={{ lang, setLang }}>{children}</LangContext.Provider>;
}

export function useI18n() {
  const { lang } = React.useContext(LangContext);
  const t = React.useCallback(
    (key: I18nKey): string => DICT[lang][key] ?? DICT.en[key],
    [lang]
  );
  return { lang, t, setLang: React.useContext(LangContext).setLang };
}
